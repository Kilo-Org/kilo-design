#!/usr/bin/env node

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clampChroma, oklch, parse } from "culori";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const TOKENS_PATH = path.join(REPO_ROOT, "tokens.json");
const OUTPUT_DIR = path.join(REPO_ROOT, "src");

const OUTPUTS = {
  webCss: path.join(OUTPUT_DIR, "tokens.web.css"),
  portableTs: path.join(OUTPUT_DIR, "tokens.ts"),
  hostMap: path.join(OUTPUT_DIR, "tokens.host-map.md"),
};

const COLOR_BUCKETS = ["brand", "status", "surface", "foreground", "border", "syntax", "diff"];
const REQUIRED_TYPE_FIELDS = ["fontFamily", "fontSize", "fontWeight", "lineHeight"];

const GENERATED_HEADER = [
  "Generated from tokens.json by `node build`.",
  "Do not edit this file by hand.",
].join(" ");

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isMetaKey(key) {
  return key.startsWith("$");
}

function cssVarName(...parts) {
  return `--${parts.join("-")}`;
}

function assertRecord(value, name) {
  if (!isRecord(value)) {
    throw new Error(`${name} must be an object.`);
  }
}

function assertStringMap(value, name) {
  assertRecord(value, name);
  for (const [key, val] of Object.entries(value)) {
    if (isMetaKey(key)) continue;
    if (typeof val !== "string") {
      throw new Error(`${name}.${key} must be a string.`);
    }
  }
}

function assertColorMap(value, name) {
  assertStringMap(value, name);
  for (const [key, val] of Object.entries(value)) {
    if (isMetaKey(key)) continue;
    if (!/^#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(val)) {
      throw new Error(`${name}.${key} must be a hex color.`);
    }
  }
}

function validateTokens(tokens) {
  assertRecord(tokens, "tokens");

  if (typeof tokens.version !== "string") {
    throw new Error("tokens.version must be a string.");
  }

  assertRecord(tokens.color, "tokens.color");
  for (const bucket of COLOR_BUCKETS) {
    assertColorMap(tokens.color[bucket], `tokens.color.${bucket}`);
  }

  assertStringMap(tokens.statusDomain, "tokens.statusDomain");
  for (const [domain, family] of Object.entries(tokens.statusDomain)) {
    if (isMetaKey(domain)) continue;
    if (!tokens.color.status[`${family}500`]) {
      throw new Error(`tokens.statusDomain.${domain} points to missing status family "${family}".`);
    }
  }

  assertRecord(tokens.typography, "tokens.typography");
  for (const [role, def] of Object.entries(tokens.typography)) {
    if (isMetaKey(role)) continue;
    assertRecord(def, `tokens.typography.${role}`);
    for (const field of REQUIRED_TYPE_FIELDS) {
      if (!(field in def)) {
        throw new Error(`tokens.typography.${role}.${field} is required.`);
      }
    }
    if (typeof def.fontFamily !== "string") throw new Error(`tokens.typography.${role}.fontFamily must be a string.`);
    if (typeof def.fontSize !== "string") throw new Error(`tokens.typography.${role}.fontSize must be a string.`);
    if (typeof def.fontWeight !== "number") throw new Error(`tokens.typography.${role}.fontWeight must be a number.`);
    if (typeof def.lineHeight !== "number") throw new Error(`tokens.typography.${role}.lineHeight must be a number.`);
    if ("letterSpacing" in def && typeof def.letterSpacing !== "string") {
      throw new Error(`tokens.typography.${role}.letterSpacing must be a string.`);
    }
    if ("textTransform" in def && typeof def.textTransform !== "string") {
      throw new Error(`tokens.typography.${role}.textTransform must be a string.`);
    }
  }

  assertStringMap(tokens.radius, "tokens.radius");
  assertStringMap(tokens.spacing, "tokens.spacing");
}

function toOklchCss(value, tokenPath) {
  const parsed = parse(value);
  if (!parsed) {
    throw new Error(`Could not parse ${tokenPath} as a color.`);
  }
  const converted = oklch(parsed);
  if (!converted) {
    throw new Error(`Could not convert ${tokenPath} to OKLCH.`);
  }
  const clamped = clampChroma(converted, "oklch", "rgb");
  return formatOklchCss(clamped);
}

function formatNumber(value, places) {
  const rounded = Math.abs(value) < Number.EPSILON ? 0 : value;
  return rounded.toFixed(places).replace(/\.?0+$/, "");
}

function formatOklchCss(color) {
  const lightness = formatNumber(color.l * 100, 3);
  const chromaValue = Math.abs(color.c ?? 0) < 0.00005 ? 0 : color.c;
  const chroma = formatNumber(chromaValue, 4);
  const hue = chromaValue === 0 ? "0" : formatNumber(((color.h ?? 0) + 360) % 360, 2);
  const alpha = color.alpha === undefined || color.alpha >= 0.9995 ? "" : ` / ${formatNumber(color.alpha, 3)}`;
  return `oklch(${lightness}% ${chroma} ${hue}${alpha})`;
}

function flattenToCssVars(tokens, { colorFormat }) {
  const out = {};

  for (const bucket of COLOR_BUCKETS) {
    for (const [name, value] of Object.entries(tokens.color[bucket])) {
      if (isMetaKey(name)) continue;
      const varName = cssVarName(bucket, name);
      out[varName] = colorFormat === "oklch" ? toOklchCss(value, `color.${bucket}.${name}`) : value;
    }
  }

  for (const [name, value] of Object.entries(tokens.radius)) {
    if (isMetaKey(name)) continue;
    out[cssVarName("radius", name)] = value;
  }

  for (const [name, value] of Object.entries(tokens.spacing)) {
    if (isMetaKey(name)) continue;
    out[cssVarName("spacing", name)] = value;
  }

  for (const [role, def] of Object.entries(tokens.typography)) {
    if (isMetaKey(role)) continue;
    out[cssVarName("type", role, "family")] = def.fontFamily;
    out[cssVarName("type", role, "size")] = def.fontSize;
    out[cssVarName("type", role, "weight")] = String(def.fontWeight);
    out[cssVarName("type", role, "leading")] = String(def.lineHeight);
    if (def.letterSpacing) out[cssVarName("type", role, "tracking")] = def.letterSpacing;
    if (def.textTransform) out[cssVarName("type", role, "transform")] = def.textTransform;
  }

  return out;
}

function generateWebCss(tokens) {
  const vars = flattenToCssVars(tokens, { colorFormat: "oklch" });
  const lines = Object.entries(vars).map(([name, value]) => `  ${name}: ${value};`);
  return [
    `/* ${GENERATED_HEADER} */`,
    ":root,",
    '[data-theme="kilo-dark"] {',
    "  color-scheme: dark;",
    ...lines,
    "}",
    "",
  ].join("\n");
}

function stringifyConst(value) {
  return JSON.stringify(value, null, 2);
}

function generatePortableTs(tokens) {
  const cssVars = flattenToCssVars(tokens, { colorFormat: "hex" });
  return [
    `// ${GENERATED_HEADER}`,
    "",
    `export const tokenVersion = ${JSON.stringify(tokens.version)} as const;`,
    "",
    `export const tokens = ${stringifyConst(tokens)} as const;`,
    "",
    `export const cssVars = ${stringifyConst(cssVars)} as const;`,
    "",
    "export type Tokens = typeof tokens;",
    "export type CssVars = typeof cssVars;",
    "export type CssVarName = keyof CssVars;",
    "",
    "export default tokens;",
    "",
  ].join("\n");
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function tokenRef(name) {
  return `\`${name}\``;
}

function tsRef(pathParts) {
  return `\`tokens.${pathParts.join(".")}\``;
}

