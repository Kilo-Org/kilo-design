function generateHostMap(tokens) {
  const domainRows = Object.entries(tokens.statusDomain).map(([domain, family]) => [
    `\`${domain}\``,
    `\`${family}\``,
    tokenRef(`--status-${family}500`),
    tsRef(["color", "status", `${family}500`]),
    `\`${ANSI_BY_FAMILY[family] ?? "default"}\``,
  ]);

  return [
    "# Kilo Token Host Map",
    "",
    `> ${GENERATED_HEADER}`,
    "",
    "This file documents how the generated token artifacts map into host environments. Product skills can add stricter per-surface recipes, but they should not redefine these token values.",
    "",
    "## Generated Artifacts",
    "",
    "- `src/tokens.web.css`: OKLCH CSS variables for browser surfaces such as Cloud and Landing.",
    "- `src/tokens.ts`: hex source values and flattened CSS-variable names for portable targets such as webviews, React Native, CLI, and native integrations.",
    "- `src/tokens.host-map.md`: this generated host mapping reference.",
    "",
    "## VS Code Webview",
    "",
    "Kilo webviews render Kilo-dark content inside VS Code chrome. They do not follow host light themes; only high-contrast host adaptations should override Kilo-dark values.",
    "",
    table(["Kilo token", "Closest `--vscode-*` host token", "Use"], VSCODE_WEBVIEW_MAP.map((row) => [tokenRef(row[0]), row[1], row[2]])),
    "",
    "## JetBrains",
    "",
    "JetBrains surfaces should read the native UIManager role where host chrome owns the surface, then use Kilo tokens for Kilo-owned content. Host-specific details stay in `kilo-jetbrains/AGENTS.md`.",
    "",
    table(["Kilo role", "UIManager role", "Use"], JETBRAINS_MAP.map((row) => [tokenRef(row[0]), row[1], row[2]])),
    "",
    "## CLI / ANSI",
    "",
    "Terminal output should keep structure and contrast first. Use ANSI colors as the nearest semantic family, not as exact color matching.",
    "",
    table(["Domain", "Status family", "Base token", "Portable token", "ANSI role"], domainRows),
    "",
    "## Notes",
    "",
    "- `brand.primary` is Kilo-owned. Do not remap it to arbitrary host accents unless a high-contrast mode requires it.",
    "- `foreground` means on-surface content, not a product brand color.",
    "- `border.inputBg` is a fill-like input token kept in the border bucket for compatibility with the current token contract.",
    "",
  ].join("\n");
}

export async function readTokens(tokensPath = TOKENS_PATH) {
  const raw = await fs.readFile(tokensPath, "utf8");
  const tokens = JSON.parse(raw);
  validateTokens(tokens);
  return tokens;
}

export async function generateTokenArtifacts({ tokensPath = TOKENS_PATH, outputDir = OUTPUT_DIR } = {}) {
  const tokens = await readTokens(tokensPath);
  const outputs = {
    webCss: path.join(outputDir, "tokens.web.css"),
    portableTs: path.join(outputDir, "tokens.ts"),
    hostMap: path.join(outputDir, "tokens.host-map.md"),
  };

  await fs.mkdir(outputDir, { recursive: true });
  await Promise.all([
    fs.writeFile(outputs.webCss, generateWebCss(tokens), "utf8"),
    fs.writeFile(outputs.portableTs, generatePortableTs(tokens), "utf8"),
    fs.writeFile(outputs.hostMap, generateHostMap(tokens), "utf8"),
  ]);

  return outputs;
}

const cliTarget = process.argv[1] ? path.resolve(process.argv[1]) : "";
const isCli = cliTarget === fileURLToPath(import.meta.url) || cliTarget === __dirname;

if (isCli) {
  try {
    const outputs = await generateTokenArtifacts();
    for (const filePath of Object.values(outputs)) {
      console.log(path.relative(REPO_ROOT, filePath));
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}

