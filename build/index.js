#!/usr/bin/env node

// Generates src/tokens.css from tokens.json. No dependencies.
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const TOKENS_PATH = path.join(REPO_ROOT, "tokens.json");
const OUTPUT_PATH = path.join(REPO_ROOT, "src", "tokens.css");

const MODES = ["dark", "light"];
const ALIAS = /^\{([a-z0-9-]+)\}$/;

function fail(message) {
  throw new Error(message);
}

function stringMap(value, name) {
  if (typeof value !== "object" || value === null || Array.isArray(value)) fail(`${name} must be an object.`);
  for (const [key, val] of Object.entries(value)) {
    if (typeof val !== "string" || val === "") fail(`${name}.${key} must be a non-empty string.`);
  }
  return value;
}

/** Follows `{role}` aliases within one mode to a literal value. */
export function resolveColor(roles, name, seen = []) {
  if (seen.includes(name)) fail(`Alias cycle: ${[...seen, name].join(" -> ")}.`);
  const value = roles[name];
  if (value === undefined) fail(`Unknown color role "${name}"${seen.length ? ` (aliased from ${seen.at(-1)})` : ""}.`);
  const alias = value.match(ALIAS);
  return alias ? resolveColor(roles, alias[1], [...seen, name]) : value;
}

export function validateTokens(tokens) {
  if (typeof tokens.version !== "string") fail("tokens.version must be a string.");
  stringMap(tokens.brand, "tokens.brand");
  stringMap(tokens.radius, "tokens.radius");
  stringMap(tokens.spacing, "tokens.spacing");

  for (const group of ["color", "shadow"]) {
    for (const mode of MODES) stringMap(tokens[group]?.[mode], `tokens.${group}.${mode}`);
    // Every role must exist in both modes, or a surface breaks when the mode flips.
    const [dark, light] = MODES.map((mode) => Object.keys(tokens[group][mode]));
    const missing = [...dark.filter((k) => !light.includes(k)), ...light.filter((k) => !dark.includes(k))];
    if (missing.length) fail(`tokens.${group}: not defined in both modes: ${missing.join(", ")}.`);
  }
  for (const mode of MODES) {
    for (const name of Object.keys(tokens.color[mode])) resolveColor(tokens.color[mode], name);
  }

  for (const [role, def] of Object.entries(tokens.typography ?? fail("tokens.typography is required."))) {
    if (typeof def.fontFamily !== "string") fail(`tokens.typography.${role}.fontFamily must be a string.`);
    if (typeof def.fontSize !== "string") fail(`tokens.typography.${role}.fontSize must be a string.`);
    if (typeof def.fontWeight !== "number") fail(`tokens.typography.${role}.fontWeight must be a number.`);
    if (typeof def.lineHeight !== "number") fail(`tokens.typography.${role}.lineHeight must be a number.`);
  }
}

const decl = (name, value) => `  --${name}: ${value};`;
const prefixed = (prefix, map) => Object.entries(map).map(([name, value]) => decl(`${prefix}-${name}`, value));

export function generateCss(tokens) {
  const shared = [
    ...prefixed("brand", tokens.brand),
    ...prefixed("radius", tokens.radius),
    ...prefixed("spacing", tokens.spacing),
    ...Object.entries(tokens.typography).flatMap(([role, def]) => [
      decl(`type-${role}-family`, JSON.stringify(def.fontFamily)),
      decl(`type-${role}-size`, def.fontSize),
      decl(`type-${role}-weight`, def.fontWeight),
      decl(`type-${role}-leading`, def.lineHeight),
      ...(def.letterSpacing ? [decl(`type-${role}-tracking`, def.letterSpacing)] : []),
      ...(def.textTransform ? [decl(`type-${role}-transform`, def.textTransform)] : []),
    ]),
  ];
  const mode = (name) => [
    `  color-scheme: ${name};`,
    ...Object.entries(tokens.color[name]).map(([role, value]) => decl(role, value.replace(ALIAS, "var(--$1)"))),
    ...prefixed("shadow", tokens.shadow[name]),
  ];
  return [
    "/* Generated from tokens.json by `node build`. Do not edit this file by hand. */",
    `/* Kilo design tokens ${tokens.version}. Dark is the default; set data-mode="light" or "dark" on any element. */`,
    ":root {",
    ...shared,
    "}",
    ':root,\n[data-mode="dark"] {',
    ...mode("dark"),
    "}",
    '[data-mode="light"] {',
    ...mode("light"),
    "}",
    "",
  ].join("\n");
}

export async function readTokens(tokensPath = TOKENS_PATH) {
  const tokens = JSON.parse(await fs.readFile(tokensPath, "utf8"));
  validateTokens(tokens);
  return tokens;
}

const cliTarget = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (cliTarget === fileURLToPath(import.meta.url) || cliTarget === __dirname) {
  try {
    await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
    await fs.writeFile(OUTPUT_PATH, generateCss(await readTokens()), "utf8");
    console.log(path.relative(REPO_ROOT, OUTPUT_PATH));
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
